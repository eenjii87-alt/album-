CREATE TABLE IF NOT EXISTS docs (app TEXT NOT NULL, path TEXT NOT NULL, parent TEXT NOT NULL, data TEXT NOT NULL, updated INTEGER NOT NULL, PRIMARY KEY (app, path));
CREATE INDEX IF NOT EXISTS docs_parent ON docs (app, parent);
CREATE TABLE IF NOT EXISTS cols (app TEXT NOT NULL, parent TEXT NOT NULL, ver INTEGER NOT NULL, PRIMARY KEY (app, parent));
CREATE TABLE IF NOT EXISTS users (email TEXT PRIMARY KEY, name TEXT, roles TEXT NOT NULL, added INTEGER);
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, email TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS codes (email TEXT PRIMARY KEY, hash TEXT NOT NULL, expires INTEGER NOT NULL, tries INTEGER NOT NULL, sent INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS assets (id TEXT PRIMARY KEY, app TEXT NOT NULL, type TEXT NOT NULL, size INTEGER NOT NULL, by TEXT, created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS config (k TEXT PRIMARY KEY, v TEXT NOT NULL);
